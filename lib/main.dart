import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'config.dart';
import 'firebase_options.dart'; // Generated by `flutterfire configure`.
import 'screens/pay.dart';
import 'screens/treasurer.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(DuesPayApp(launchCode: codeFromLaunchUrl()));
}

class DuesPayApp extends StatelessWidget {
  const DuesPayApp({super.key, this.launchCode});

  /// Set when the web app was opened from a pay link (?code=...).
  final String? launchCode;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'DuesPay',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: const Color(0xFF0F766E)),
        useMaterial3: true,
        inputDecorationTheme: const InputDecorationTheme(
          border: OutlineInputBorder(),
        ),
      ),
      // On wide screens (web, tablets) keep the app phone-width and centred
      // instead of stretching forms across the whole window.
      builder: (context, child) => ColoredBox(
        color: const Color(0xFFEFF5F4),
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 560),
            child: child,
          ),
        ),
      ),
      home: HomeScreen(launchCode: launchCode),
    );
  }
}

class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key, this.launchCode});

  final String? launchCode;

  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  @override
  void initState() {
    super.initState();
    final code = widget.launchCode;
    if (code != null) {
      // Opened from a pay link: go straight to that due.
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (!mounted) return;
        Navigator.of(context).push(
          MaterialPageRoute(builder: (_) => EnterCodeScreen(initialCode: code)),
        );
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Scaffold(
      body: SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              const Spacer(),
              Icon(Icons.receipt_long, size: 56, color: theme.colorScheme.primary),
              const SizedBox(height: 16),
              Text(
                'DuesPay',
                textAlign: TextAlign.center,
                style: theme.textTheme.headlineLarge
                    ?.copyWith(fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 8),
              Text(
                'Collect departmental dues by bank transfer.\nNo screenshots, no spreadsheets.',
                textAlign: TextAlign.center,
                style: theme.textTheme.bodyLarge,
              ),
              const Spacer(),
              FilledButton.icon(
                icon: const Icon(Icons.payments_outlined),
                label: const Padding(
                  padding: EdgeInsets.symmetric(vertical: 14),
                  child: Text('Pay a due'),
                ),
                onPressed: () => Navigator.of(context).push(
                  MaterialPageRoute(builder: (_) => const EnterCodeScreen()),
                ),
              ),
              const SizedBox(height: 12),
              OutlinedButton.icon(
                icon: const Icon(Icons.dashboard_outlined),
                label: const Padding(
                  padding: EdgeInsets.symmetric(vertical: 14),
                  child: Text("I'm a treasurer"),
                ),
                onPressed: () => Navigator.of(context).push(
                  MaterialPageRoute(builder: (_) => const TreasurerGate()),
                ),
              ),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
    );
  }
}
